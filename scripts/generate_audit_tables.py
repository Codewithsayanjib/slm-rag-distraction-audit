# ── Helper: Wilson 95% CI ───────────────────────────────────────────────────
def wilson_ci(successes: int, n: int) -> tuple[float, float]:
    """Return (low, high) of a 95 % Wilson score confidence interval."""
    if n == 0:
        return (0.0, 0.0)
    lo, hi = proportion_confint(successes, n, alpha=CI_ALPHA, method="wilson")
    return float(lo), float(hi)


def ci_non_overlapping(lo1: float, hi1: float,
                       lo2: float, hi2: float) -> bool:
    """Return True when two intervals are strictly non-overlapping."""
    return hi1 < lo2 or hi2 < lo1


